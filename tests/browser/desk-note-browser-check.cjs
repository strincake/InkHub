const {chromium}=require('playwright');
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'../..');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'plugins/desk-note/plugin.json'),'utf8'));
const settings=Object.fromEntries(manifest.settings.map(f=>[f.key,f.default]));
const out=path.join(root,'artifacts/tests/browser/desk-note');fs.mkdirSync(out,{recursive:true});
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH});
 try {
  const page=await browser.newPage({viewport:{width:1400,height:850}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.route('http://notes.test/**',route=>route.fulfill({contentType:'text/html; charset=utf-8',body:route.request().url().endsWith('/home')?fs.readFileSync(path.join(root,'plugins/desk-note/home.html'),'utf8'):`<html><body style="margin:0;background:#edf2f8"><iframe style="border:0;width:100%;height:800px" sandbox="allow-scripts" src="/home"></iframe><script>
   window.settings=${JSON.stringify(settings)};window.fail=false;window.saved=null;
   window.send=m=>document.querySelector('iframe').contentWindow.postMessage({protocol:'screen-plugin-ui-v1',...m},'*');
   window.context=()=>send({type:'context',settings,state:{},enabled:true,appearance:{resolved:'light'}});
   addEventListener('message',e=>{if(e.data?.protocol!=='screen-plugin-ui-v1')return;const m=e.data;if(m.type==='ready')context();if(m.type==='save_settings'){saved=m.settings;if(!fail){settings=m.settings;context()}send({type:'result',request_id:m.request_id,ok:!fail,error:fail?'模拟保存失败':undefined})}});
   </script></body></html>`}));
  await page.goto('http://notes.test/');
  const frame=page.frameLocator('iframe');
  await frame.locator('#add-note').waitFor();
  assert.equal(await frame.locator('.note-item').count(),3);
  await frame.locator('#show-title').uncheck();
  await frame.locator('#notes').fill('第一行正文\n\n第二行正文');
  assert.equal(await frame.locator('.note-item[aria-pressed=true] .note-name').textContent(),'第一行正文 第二行正文');
  assert.equal(await frame.locator('#title-row').isVisible(),false);
  const canvas=frame.locator('#preview');
  const firstImage=await canvas.evaluate(c=>c.toDataURL());
  await frame.locator('#font-size').fill('48');
  assert.notEqual(await canvas.evaluate(c=>c.toDataURL()),firstImage);
  await frame.locator('#add-note').click();
  assert.equal(await frame.locator('.note-item').count(),4);
  await frame.locator('#notes').fill('新便签正文');
  await frame.locator('#show-title').check();
  await frame.locator('#title').fill('新标题');
  await frame.locator('.note-item').first().click();
  assert.equal(await frame.locator('#notes').inputValue(),'第一行正文\n\n第二行正文');
  assert.equal(await frame.locator('#font-size').inputValue(),'48');
  await page.evaluate(()=>context());
  assert.equal(await frame.locator('#notes').inputValue(),'第一行正文\n\n第二行正文');
  await page.evaluate(()=>fail=true);
  await frame.locator('#save').click();
  await frame.locator('#message').filter({hasText:'模拟保存失败'}).waitFor();
  assert.equal(await frame.locator('#notes').inputValue(),'第一行正文\n\n第二行正文');
  await page.evaluate(()=>fail=false);
  await frame.locator('#save').click();
  await frame.locator('#message').filter({hasText:'已保存'}).waitFor();
  const saved=await page.evaluate(()=>saved);
  assert.equal(saved.document.notes.length,4);
  assert.equal(saved.document.notes[0].text,'第一行正文\n\n第二行正文');
  assert.equal(saved.document.notes[0].show_title,false);
  assert.equal(saved.document.notes[0].font_size,48);
  assert.equal(saved.active_note,saved.document.notes[0].id);
  assert.equal(await frame.locator('#editor #delete-note').count(),1);
  await frame.locator('.note-item').last().click();
  assert.equal(await frame.locator('#title').inputValue(),'新标题');
  await frame.locator('#delete-note').click();
  assert.equal(await frame.locator('.note-item').count(),3);
  for(let i=0;i<3;i++)await frame.locator('#delete-note').click();
  assert.equal(await frame.locator('#notes').isDisabled(),true);
  await frame.locator('#save').click();
  await frame.locator('#message').filter({hasText:'已保存'}).waitFor();
  assert.deepEqual((await page.evaluate(()=>saved)).document.notes,[]);
  await frame.locator('#add-note').click();
  for(let i=0;i<15;i++)await frame.locator('#add-note').click();
  const scroll=await frame.locator('#note-list').evaluate(e=>({height:e.clientHeight,scroll:e.scrollHeight}));
  assert.ok(scroll.scroll>scroll.height);
  await frame.locator('#notes').fill('完成最重要的一件事。\n站起来，喝一杯水。');
  await frame.locator('#show-title').uncheck();
  await page.screenshot({path:path.join(out,'light.png')});
  await page.evaluate(()=>send({type:'appearance',appearance:{resolved:'dark'}}));
  await page.screenshot({path:path.join(out,'dark.png')});
  await page.setViewportSize({width:680,height:1000});
  await page.screenshot({path:path.join(out,'narrow.png')});
  assert.equal(await frame.locator('body').evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  // Compact JSON fits, but the host's spaced JSON exceeds the document budget.
  await frame.locator('#save').click();
  await frame.locator('#message').filter({hasText:'已保存'}).waitFor();
  await page.evaluate(()=>{
   const n={id:'limit',title:'',text:'',show_title:false,font_size:24};
   const document={version:2,notes:[n]};n.text='x'.repeat(32768-JSON.stringify(document).length);
   settings={...settings,document,active_note:n.id};context();
  });
  await frame.locator('#message').filter({hasText:'已连接'}).waitFor();
  await frame.locator('#save').click();
  await frame.locator('#message').filter({hasText:'便签内容过多'}).waitFor();
  assert.deepEqual(errors,[]);
  console.log('PASS: legacy migration, multiline, live preview, per-note title/font, draft switching, failed/successful save, deletion/empty recovery, scrolling, themes and narrow layout');
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
